#!/usr/bin/env python3
"""Regenerate the bundled NCAA directory from public ESPN team/membership data."""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import date
import json
from pathlib import Path
import re
from urllib.request import urlopen

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--season", type=int, default=date.today().year)
parser.add_argument("--cache-dir", type=Path, help="Optional local response cache for regeneration")
args = parser.parse_args()
assert 2020 <= args.season <= 2100
paths = {"CFB-teams": "football/college-football", "CBB-teams": "basketball/mens-college-basketball", "WCBB-teams": "basketball/womens-college-basketball", "BBASE-teams": "baseball/college-baseball"}
urls = {key: f"https://site.api.espn.com/apis/site/v2/sports/{path}/teams?limit=1000" for key, path in paths.items()}
urls.update({f"CFB-members-{group}": f"https://sports.core.api.espn.com/v2/sports/football/leagues/college-football/seasons/{args.season}/types/2/groups/{group}/teams?limit=1000" for group in (80, 81)})

def fetch(item):
    key, url = item
    cached = args.cache_dir / f"{key}.json" if args.cache_dir else None
    if cached and cached.exists():
        raw = cached.read_bytes()
    else:
        with urlopen(url, timeout=20) as response:
            raw = response.read(8 * 1024 * 1024 + 1)
        if cached:
            cached.parent.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(raw)
    assert len(raw) <= 8 * 1024 * 1024
    return key, json.loads(raw)

with ThreadPoolExecutor(max_workers=4) as pool:
    data = dict(pool.map(fetch, urls.items()))
members = {re.search(r"/teams/(\d+)", item["$ref"]).group(1) for group in (80, 81) for item in data[f"CFB-members-{group}"]["items"]}
blocks = []
school_names = {"UConn": ["Connecticut"], "LSU": ["Louisiana State"], "USC": ["Southern California", "Southern Cal"], "Ole Miss": ["Mississippi"], "BYU": ["Brigham Young"], "UCF": ["Central Florida"], "UNLV": ["Nevada Las Vegas"], "SMU": ["Southern Methodist"], "UCLA": ["California Los Angeles"]}
for key, league in (("CFB-teams", "NCAAF"), ("CBB-teams", "NCAAM"), ("WCBB-teams", "NCAAW"), ("BBASE-teams", "NCAABSB")):
    teams = [item["team"] for item in data[key]["sports"][0]["leagues"][0]["teams"]]
    if league == "NCAAF":
        # New/inactive schools can appear in season membership before the
        # directory; resolve those IDs while excluding postseason placeholders.
        missing = members - {team["id"] for team in teams}
        assert len(missing) <= 32
        missing_urls = [(f"CFB-team-{team}", f"https://site.api.espn.com/apis/site/v2/sports/football/college-football/teams/{team}") for team in sorted(missing)]
        with ThreadPoolExecutor(max_workers=4) as pool:
            extras = [reply["team"] for _, reply in pool.map(fetch, missing_urls)]
        teams += [team for team in extras if team.get("groups", {}).get("isConference") and not re.search(r"\b(tba|tbd|all[- ]?stars?|winner)\b", team["displayName"], re.I)]
        teams = [team for team in teams if team["id"] in members]
        # Membership replies also contain postseason TBD slots, absent from
        # the public school directory. Only named schools belong in the picker.
    assert 200 <= len(teams) <= 500
    rows = []
    for team in sorted(teams, key=lambda team: team["displayName"]):
        aliases = list(dict.fromkeys([team.get(field, "") for field in ("location", "shortDisplayName", "nickname", "abbreviation")] + school_names.get(team.get("location"), [])))
        logo = next((logo["href"] for logo in team.get("logos", []) if logo.get("href", "").startswith("https://a.espncdn.com/")), "-")
        values = [team["id"], team["displayName"], "|".join(alias for alias in aliases if alias and alias != team["displayName"]), logo]
        assert values[0].isdigit() and all(not any(char in value for char in ('\n', '\t', '$', '"')) for value in values)
        rows.append("\t".join(values))
    body = "\n".join(rows)
    assert len(body.encode()) < 60000
    blocks.append('read("' + league + '", """\n' + body + '\n""")')
    print(f"{league}: {len(teams)} bundled teams")
source = f'''package io.github.mot1us.spare

/** Generated by scripts/update-college-teams.py; ESPN {args.season} FBS/FCS and Division I teams. */
internal object SportsCollegeTeams {{
    private fun read(league: String, data: String) = data.trim().lineSequence().map {{ row ->
        val fields = row.split('\\t')
        SportsTeam("${{league.lowercase(java.util.Locale.ROOT)}}:${{fields[0]}}", league, fields[1],
            (listOf(fields[1]) + fields[2].split('|')).distinct(), fields[0], logo = fields[3].takeUnless {{ it == "-" }}.orEmpty())
    }}.toList()
    val teams: List<SportsTeam> by lazy {{
        {(' + ' + chr(10) + '        ').join(blocks)}
    }}
}}
'''
target = Path(__file__).resolve().parents[1] / "app/src/main/java/io/github/mot1us/spare/SportsCollegeTeams.kt"
target.write_text(source)
